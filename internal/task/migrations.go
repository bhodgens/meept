package task

import (
	"database/sql"
	"fmt"

	"github.com/caimlas/meept/internal/migrate"
)

// This file holds the declared schema history for the tasks database,
// which is SHARED by Store (tasks/session_tasks tables) and StepStore
// (task_steps/task_state_transitions tables): user_version is
// per-database, so both stores' migrations live in one contiguous
// history. Central contract: internal/migrate
// (docs/workflows/migrations.md).

// storeMigrations is the declared schema history for the tasks database.
// Validated once at package init; Apply is called from Store.migrate.
var storeMigrations = func() *migrate.Registry {
	r, err := migrate.NewRegistry("task", allMigrations())
	if err != nil {
		panic(fmt.Sprintf("task store migration registry invalid: %v", err))
	}
	return r
}()

// allMigrations returns the complete contiguous history: the tasks column
// steps 1..8 plus the task_steps column steps 9..30.
func allMigrations() []migrate.Migration {
	return append(migrations(), migrate.ColumnSteps(9, "task_steps", taskStepsColumnSpecs)...)
}

// migrations returns the tasks-table half of the history. Each tasks
// column is its own guarded step: the CREATE script already carries most
// of them (fresh databases skip every step except goal_id), while
// pre-registry databases may lack any subset (the old
// tolerate-duplicate-column ALTERs added whichever were missing).
func migrations() []migrate.Migration {
	return []migrate.Migration{
		columnStep(1, "tasks.memory_refs", "tasks", "memory_refs", "TEXT"),
		columnStep(2, "tasks.context_query", "tasks", "context_query", "TEXT"),
		columnStep(3, "tasks.inherited_from", "tasks", "inherited_from", "TEXT"),
		columnStep(4, "tasks.created_memories", "tasks", "created_memories", "TEXT"),
		columnStep(5, "tasks.assigned_agent", "tasks", "assigned_agent", "TEXT"),
		columnStep(6, "tasks.token_usage", "tasks", "token_usage", "INTEGER DEFAULT 0"),
		{
			// Goal linkage (goal-completion leaf 02, C3): every task
			// traces to its owning goal. Legacy rows keep NULL goal_id,
			// which scans to "". NOT in the CREATE script — this step
			// is its only source.
			Version: 7,
			Name:    "tasks.goal_id goal linkage",
			SQL:     "ALTER TABLE tasks ADD COLUMN goal_id TEXT",
			Guard:   tasksColumnMissingGuard("goal_id"),
		},
		{
			// Execution start stamp ("completed in 0s" defect, 2026-10-22):
			// SetState sets StartedAt on pending→active, but the store never
			// persisted it — the finalize path re-reads the task, StartedAt
			// came back zero, and task.completed carried execution_time "0s"
			// for a 35s job. Legacy rows keep NULL (scan to zero time).
			Version: 8,
			Name:    "tasks.started_at execution start stamp",
			SQL:     "ALTER TABLE tasks ADD COLUMN started_at TEXT",
			Guard:   tasksColumnMissingGuard("started_at"),
		},
	}
}

// taskStepsColumnSpecs is the task_steps column history in registry order
// (versions 9..30, generated by ColumnSteps). One guarded step per
// column: pre-registry task databases carried NO version stamps, so they
// can be missing an arbitrary SUBSET of these columns and a batch step
// would die on the first already-present column.
var taskStepsColumnSpecs = [][2]string{
	{"revision_count", "INTEGER DEFAULT 0"},
	{"recommendations", "TEXT"},
	{"evidence", "TEXT"},
	{"claims", "TEXT"},
	{"validated", "BOOLEAN DEFAULT FALSE"},
	{"validation_error", "TEXT"},
	{"token_usage", "INTEGER DEFAULT 0"},
	{"memory_refs", "TEXT"},
	{"accumulated_context", "TEXT"},
	{"model_override", "TEXT"},
	{"checklist", "TEXT"},
	{"phase", "TEXT"},
	{"checkpoint_gate", "BOOLEAN DEFAULT FALSE"},
	{"is_handoff", "BOOLEAN DEFAULT FALSE"},
	{"conversation_id", "TEXT"},
	// Originating-session provenance (tree 04 leaf 02, audit R4).
	{"session_id", "TEXT"},
	// Successor hint (agent-routing tree leaf 03): advisory
	// suggested-next hint copied from the finished step-job envelope.
	{"suggested_next_hint", "TEXT"},
	// Output-filter retry accounting (output-filters tree, leaf 03):
	// filter rejections persist their own counter + last reason beside
	// the evidence-validation verdict columns.
	{"filter_retry_count", "INTEGER DEFAULT 0"},
	{"filter_error", "TEXT"},
	// Review verdict persistence (tiered-iteration leaf 03): the
	// ReviewStep verdict was previously ephemeral (bus event only);
	// persisting it beside the step lets the critic's evidence
	// assembler read prior verdicts back per session.
	{"review_verdict", "TEXT"},
	{"review_reason", "TEXT"},
	{"review_at", "TEXT"},
}

// columnStep builds a guarded single-column tasks migration: run when the
// column is missing (pre-registry legacy database), skip when the CREATE
// script already provided it (fresh database) or a previous open added it.
func columnStep(version int, name, table, column, colType string) migrate.Migration {
	return migrate.Migration{
		Version: version,
		Name:    name,
		SQL:     "ALTER TABLE " + table + " ADD COLUMN " + column + " " + colType,
		Guard:   tasksColumnMissingGuard(column),
	}
}

// tasksColumnMissingGuard reports a step as needed exactly when the tasks
// table lacks column (legacy tolerate-duplicate-column ALTER semantics
// expressed as a predicate).
func tasksColumnMissingGuard(column string) func(*sql.DB) (bool, error) {
	return func(db *sql.DB) (bool, error) {
		exists, err := migrate.ColumnExists(db, "tasks", column)
		return !exists, err
	}
}
