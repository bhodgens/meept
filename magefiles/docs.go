const gomarkdocPkg = "github.com/princjef/gomarkdoc/cmd/gomarkdoc@latest"

// modulePath is the main module's import path. DocsGenerate only ever
// documents packages that resolve inside this module.
const modulePath = "github.com/caimlas/meept"

// gomarkdocHeader is the first line gomarkdoc writes into every file it
// generates. It marks a file as generator output (as opposed to a hand-written
// doc that happens to live in the same directory).
const gomarkdocHeader = "<!-- Code generated by gomarkdoc. DO NOT EDIT -->"

// DocsGenerate runs gomarkdoc over key internal packages and outputs
// markdown documentation to docs/reference/generated/. This replaces
// the legacy cmd/gendoc tool with a godoc-comment-driven approach
// that is better suited for the MkDocs-based documentation site.
//
// Packages documented:
//   - internal/config      (configuration schema)
//   - internal/agent       (agent loop and orchestration)
//   - internal/bus         (pub/sub message bus)
//   - internal/security    (security engine, sanitizer, tirith)
//   - internal/llm         (LLM client and provider resolution)
//   - internal/memory      (episodic, task, and graph memory)
//   - internal/tools       (tool registry and builtins)
//   - internal/skills      (skill discovery and execution)
//   - internal/scheduler   (cron-based job scheduling)
//
// Only packages that resolve inside the real module tree are documented, and
// generated files this generator no longer produces are removed, so the output
// directory cannot accumulate stale content.
func DocsGenerate() error {
	const outputDir = "docs/reference/generated"

	// Determine module root by walking up from this file to find go.mod.
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		return fmt.Errorf("cannot determine magefile location")
	}
	root := filepath.Dir(filepath.Dir(filename))

	// Map of Go package import paths to output filenames.
	// Keys are package paths relative to the module root.
	// Values are the markdown file names under outputDir.
	packages := map[string]string{
		"github.com/caimlas/meept/internal/config":    "config.md",
		"github.com/caimlas/meept/internal/agent":     "agent.md",
		"github.com/caimlas/meept/internal/bus":       "bus.md",
		"github.com/caimlas/meept/internal/security":  "security.md",
		"github.com/caimlas/meept/internal/llm":       "llm.md",
		"github.com/caimlas/meept/internal/memory":    "memory.md",
		"github.com/caimlas/meept/internal/tools":     "tools.md",
		"github.com/caimlas/meept/internal/skills":    "skills.md",
		"github.com/caimlas/meept/internal/scheduler": "scheduler.md",
	}

	// Ensure gomarkdoc is available. If not in PATH, install it to GOPATH/bin.
	gomarkdocBin, err := resolveGomarkdoc()
	if err != nil {
		return fmt.Errorf("gomarkdoc setup failed: %w", err)
	}

	// Ensure output directory exists.
	outDir := filepath.Join(root, outputDir)
	if err := os.MkdirAll(outDir, 0o755); err != nil { //nolint:gosec // docs directory is intentionally world-readable
		return fmt.Errorf("failed to create output directory %s: %w", outDir, err)
	}

	// Resolve every documented package to its directory in the real module tree
	// and drop anything that lands in a nested checkout. Claude Code worktrees
	// live under .claude/worktrees/<agent>/ and are separate git checkouts with
	// their own go.mod, so their sources can be older than this module's;
	// documenting them would publish stale content into the generated docs.
	type docTarget struct {
		pkg     string
		outFile string
	}
	targets := make([]docTarget, 0, len(packages))
	for pkg, outFile := range packages {
		if insideSeparateCheckout(root, packageDir(root, pkg)) {
			fmt.Fprintf(os.Stderr, "warning: skipping %s: resolves outside the meept module tree (nested checkout)\n", pkg)
			continue
		}
		targets = append(targets, docTarget{pkg: pkg, outFile: outFile})
	}
	// Sort so index.md and .nav.yml are byte-identical between runs; map
	// iteration order is randomized, which otherwise makes every regeneration
	// produce a spurious diff.
	sort.Slice(targets, func(i, j int) bool { return targets[i].outFile < targets[j].outFile })

	produced := make([]string, 0, len(targets))
	for _, target := range targets {
		dest := filepath.Join(outDir, target.outFile)
		fmt.Printf("Generating %s from %s\n", target.outFile, target.pkg)

		cmd := exec.Command(gomarkdocBin, "--output", dest, "--format", "plain", target.pkg)
		cmd.Dir = root

		if out, err := cmd.CombinedOutput(); err != nil {
			// gomarkdoc may fail on packages with no exported symbols;
			// log a warning and continue rather than aborting.
			fmt.Fprintf(os.Stderr, "warning: gomarkdoc failed for %s: %v\n%s\n", target.pkg, err, out)
		}
		// Record the file even when gomarkdoc failed so a transient failure
		// never makes the pruner below delete a doc that is still maintained.
		produced = append(produced, target.outFile)
	}

	// Remove generated files this run did not produce: a stray or renamed
	// gomarkdoc artifact otherwise lingers forever with whatever (stale) source
	// it was written from, since nothing regenerates it.
	removed, err := pruneGeneratedOrphans(outDir, produced)
	if err != nil {
		return err
	}
	for _, name := range removed {
		fmt.Printf("Removed stale generated file %s (no longer produced by this generator)\n", name)
	}

	// Generate index.md with a table of contents pointing to each generated file.
	index := `# Generated Package Documentation

This directory contains documentation auto-generated from Go source code using [gomarkdoc](https://github.com/princjef/gomarkdoc).

## Packages

| Package | Description |
|---------|-------------|
`
	for _, target := range targets {
		index += fmt.Sprintf("| [%s](%s) | %s |\n", filepath.Base(target.pkg), target.outFile, target.pkg)
	}

	if err := os.WriteFile(filepath.Join(outDir, "index.md"), []byte(index), 0o644); err != nil { //nolint:gosec // docs file
		return fmt.Errorf("failed to write index.md: %w", err)
	}

	// Update .nav.yml with the generated files.
	nav := "nav:\n"
	for _, target := range targets {
		nav += fmt.Sprintf("  - %s\n", target.outFile)
	}
	nav += "  - index.md\n"
	if err := os.WriteFile(filepath.Join(outDir, ".nav.yml"), []byte(nav), 0o644); err != nil { //nolint:gosec // config file
		return fmt.Errorf("failed to write .nav.yml: %w", err)
	}

	fmt.Printf("Done. Generated %d documentation files in %s\n", len(targets)+1, outputDir)
	return nil
}

// DocsCheck verifies that generated docs are up-to-date by comparing
// them against freshly generated output. Returns an error if any file
// differs, suitable for use in CI.
func DocsCheck() error {
	const outputDir = "docs/reference/generated"

	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		return fmt.Errorf("cannot determine magefile location")
	}
	root := filepath.Dir(filepath.Dir(filename))

	// Ensure gomarkdoc is available.
	_, err := exec.LookPath("gomarkdoc")
	if err != nil {
		return fmt.Errorf("gomarkdoc not found in PATH; run 'go install github.com/princjef/gomarkdoc/cmd/gomarkdoc@latest'")
	}

	packages := []struct {
		pkg     string
		outFile string
	}{
		{"github.com/caimlas/meept/internal/config", "config.md"},
		{"github.com/caimlas/meept/internal/agent", "agent.md"},
		{"github.com/caimlas/meept/internal/bus", "bus.md"},
		{"github.com/caimlas/meept/internal/security", "security.md"},
		{"github.com/caimlas/meept/internal/llm", "llm.md"},
		{"github.com/caimlas/meept/internal/memory", "memory.md"},
		{"github.com/caimlas/meept/internal/tools", "tools.md"},
		{"github.com/caimlas/meept/internal/skills", "skills.md"},
		{"github.com/caimlas/meept/internal/scheduler", "scheduler.md"},
	}

	stale := false
	keep := make([]string, 0, len(packages)+1)
	for _, p := range packages {
		keep = append(keep, p.outFile)
		if insideSeparateCheckout(root, packageDir(root, p.pkg)) {
			stale = true
			fmt.Fprintf(os.Stderr, "STALE: %s resolves outside the meept module tree (nested checkout)\n", p.pkg)
			continue
		}
		dest := filepath.Join(root, outputDir, p.outFile)
		cmd := exec.Command("gomarkdoc", "--output", dest, "--format", "plain", "--check", p.pkg)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			stale = true
			fmt.Fprintf(os.Stderr, "STALE: %s (%s)\n%s\n", p.outFile, p.pkg, out)
		}
	}
	keep = append(keep, "index.md")

	// A generated file this generator no longer produces is stale by
	// definition: nothing will ever rewrite it.
	orphans, err := generatedOrphans(filepath.Join(root, outputDir), keep)
	if err != nil {
		return err
	}
	if len(orphans) > 0 {
		stale = true
		fmt.Fprintf(os.Stderr, "STALE: generated file(s) no longer produced by the generator: %s\n", strings.Join(orphans, ", "))
	}

	if stale {
		return fmt.Errorf("generated docs are stale; run 'mage docsGenerate' to regenerate")
	}
	fmt.Println("All generated docs are up-to-date.")
	return nil
}

// DocsClean removes all generated documentation files.
func DocsClean() error {
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		return fmt.Errorf("cannot determine magefile location")
	}
	root := filepath.Dir(filepath.Dir(filename))
	outDir := filepath.Join(root, "docs", "reference", "generated")

	entries, err := os.ReadDir(outDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("failed to read generated dir: %w", err)
	}

	for _, entry := range entries {
		if entry.Name() == ".nav.yml" {
			continue
		}
		if err := os.Remove(filepath.Join(outDir, entry.Name())); err != nil {
			return fmt.Errorf("failed to remove %s: %w", entry.Name(), err)
		}
		fmt.Printf("Removed %s\n", entry.Name())
	}

	fmt.Println("Cleaned generated documentation files.")
	return nil
}

// DocsInstall ensures gomarkdoc is available in GOPATH/bin.
func DocsInstall() error {
	_, err := resolveGomarkdoc()
	return err
}

// packageDir resolves a package import path inside modulePath to its directory
// under root. Import paths outside modulePath keep their own path, which
// insideSeparateCheckout then rejects as outside the module tree.
func packageDir(root, pkg string) string {
	rel := strings.TrimPrefix(pkg, modulePath)
	rel = strings.TrimPrefix(rel, "/")
	return filepath.Join(root, filepath.FromSlash(rel))
}

// insideSeparateCheckout reports whether dir lies inside a checkout or Go module
// nested under root — one carrying its own .git or go.mod between root and dir —
// or outside root entirely.
//
// Nested checkouts are a real hazard for generated docs: Claude Code worktrees
// live under .claude/worktrees/<agent>/, each a separate git checkout with its
// own go.mod pinned to some other commit. Their sources are older than this
// module's, so documenting them emits stale content that silently contradicts
// the code the repo actually builds.
func insideSeparateCheckout(root, dir string) bool {
	rel, err := filepath.Rel(root, dir)
	if err != nil {
		return true
	}
	if rel == "." {
		return false // the module root itself
	}
	if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return true // outside the module tree entirely
	}
	cur := root
	for _, part := range strings.Split(rel, string(filepath.Separator)) {
		cur = filepath.Join(cur, part)
		for _, marker := range []string{".git", "go.mod"} {
			if _, err := os.Stat(filepath.Join(cur, marker)); err == nil {
				return true
			}
		}
	}
	return false
}

// generatedOrphans returns the names of *.md files in outDir that carry
// gomarkdoc's generated header but are not in keep (the set the generator
// currently produces). Hand-written files are never reported, so a doc that
// merely lives in this directory is left alone.
func generatedOrphans(outDir string, keep []string) ([]string, error) {
	keepSet := make(map[string]bool, len(keep))
	for _, name := range keep {
		keepSet[name] = true
	}
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return nil, fmt.Errorf("failed to read %s: %w", outDir, err)
	}

	var orphans []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".md") || keepSet[name] {
			continue
		}
		generated, err := hasGoMarkdocHeader(filepath.Join(outDir, name))
		if err != nil || !generated {
			continue
		}
		orphans = append(orphans, name)
	}
	sort.Strings(orphans)
	return orphans, nil
}

// pruneGeneratedOrphans removes the files reported by generatedOrphans and
// returns the names it removed.
func pruneGeneratedOrphans(outDir string, keep []string) ([]string, error) {
	orphans, err := generatedOrphans(outDir, keep)
	if err != nil {
		return nil, err
	}
	for _, name := range orphans {
		if err := os.Remove(filepath.Join(outDir, name)); err != nil {
			return nil, fmt.Errorf("failed to remove stale generated file %s: %w", name, err)
		}
	}
	return orphans, nil
}

// hasGoMarkdocHeader reports whether path starts with gomarkdoc's generated
// header, marking it as generator output rather than hand-written prose.
func hasGoMarkdocHeader(path string) (bool, error) {
	f, err := os.Open(path) //nolint:gosec // reading a generated docs file in the repo
	if err != nil {
		return false, err
	}
	defer func() { _ = f.Close() }()

	head := make([]byte, len(gomarkdocHeader))
	if _, err := io.ReadFull(f, head); err != nil {
		return false, err
	}
	return string(head) == gomarkdocHeader, nil
}

// resolveGomarkdoc finds or installs the gomarkdoc binary.
// It first checks PATH, then falls back to GOPATH/bin, and finally
// installs it via "go install" if neither exists.
func resolveGomarkdoc() (string, error) {
	// Check PATH first.
	if bin, err := exec.LookPath("gomarkdoc"); err == nil {
		return bin, nil
	}

	// Check GOPATH/bin explicitly (may not be in PATH).
	gopath := os.Getenv("GOPATH")
	if gopath == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("cannot determine GOPATH: %w", err)
		}
		gopath = filepath.Join(home, "go")
	}
	candidate := filepath.Join(gopath, "bin", "gomarkdoc")
	if _, err := os.Stat(candidate); err == nil {
		return candidate, nil
	}

	// Install it.
	fmt.Println("Installing gomarkdoc...")
	if err := sh.RunV("go", "install", gomarkdocPkg); err != nil {
		return "", fmt.Errorf("failed to install gomarkdoc: %w", err)
	}
	return candidate, nil
}
